async def ai_reply(messages, api_key, model, base_url):
    if not api_key:
        return None, "🔑 ИИ пока не подключён: добавь ключ OpenRouter в переменную AI_API_KEY на Render."
    try:
        async with httpx.AsyncClient(timeout=45) as client:
            response = await client.post(
                base_url.rstrip("/") + "/chat/completions",
                headers={
                    "Authorization": f"Bearer {api_key}",
                    "Content-Type": "application/json",
                    "HTTP-Referer": "https://logovo-ai.onrender.com",
                    "X-Title": "Логово Знаний ИИ",
                },
                json={"model": model, "messages": messages, "temperature": 0.8, "max_tokens": 1200},
            )
            if response.status_code == 429:
                return None, "⏳ Бесплатный лимит ИИ сейчас исчерпан или запросов слишком много. Попробуй немного позже."
            response.raise_for_status()
            data = response.json()
            answer = data["choices"][0]["message"]["content"]
            if not answer:
                return None, "ИИ вернул пустой ответ. Попробуй ещё раз."
            return answer[:3500], None
    except httpx.HTTPStatusError as exc:
        if exc.response.status_code in (401, 403):
            return None, "🔐 OpenRouter не принял API-ключ. Проверь AI_API_KEY в Render."
        return None, f"⚠️ OpenRouter вернул ошибку {exc.response.status_code}. Попробуй позже."
    except (httpx.HTTPError, KeyError, ValueError):
        return None, "⚠️ Не удалось связаться с ИИ. Проверь настройки OpenRouter и попробуй позже."
