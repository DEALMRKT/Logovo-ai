def make_prompt():
    return ("Ты — сценарист интерактивной истории. Создай оригинальный сюжет на 5 сцен. "
            "Добавь атмосферу, неожиданный поворот, 3 персонажей с разными целями и выбор в конце каждой сцены. "
            "Не используй клише и сохраняй логичность событий.")
async def ai_reply(prompt, api_key, model, base_url):
    if not api_key:
        return ("🧪 <b>Демо-режим:</b> ключ ИИ пока не подключён.\n\n"
                "Бот уже умеет создавать встроенные сюжеты. Для полноценного ИИ владелец добавит AI_API_KEY в Render Environment.")
    try:
        async with httpx.AsyncClient(timeout=35) as client:
            response = await client.post(
                base_url.rstrip("/") + "/chat/completions",
                headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
                json={"model": model, "messages":[{"role":"system","content":"Ты дружелюбный русскоязычный помощник и сценарист."},{"role":"user","content":prompt}]}
            )
            response.raise_for_status()
            data = response.json()
            return data["choices"][0]["message"]["content"][:3900]
    except Exception:
        return "⚠️ Не удалось получить ответ от ИИ. Проверь AI_API_KEY, AI_MODEL и AI_BASE_URL в Render."
